function toLesson(s: TextSpec, i: number): Lesson {
  return {
    slug: s.slug,
    num: 15 + i,
    title: s.title,
    author: s.author,
    summary: s.genre,
    sections: [
      { id: "main", kicker: "01", title: "الفكرة الرئيسة", blocks: [{ t: "example", text: s.main }] },
      { id: "subs", kicker: "02", title: "الأفكار الفرعية", blocks: [{ t: "steps", items: s.subs.map((x, k) => ({ title: `الفكرة ${["الأولى", "الثانية", "الثالثة", "الرابعة", "الخامسة"][k]}`, body: x })) }] },
      { id: "vocab", kicker: "03", title: "المعجم والمفردات", blocks: [{ t: "table", head: ["الكلمة", "المعنى"], rows: s.vocab.map(([a, b]) => [a, b]) }] },
      { id: "images", kicker: "04", title: "الصور البلاغية", blocks: [{ t: "cards", items: s.images }] },
      { id: "evidence", kicker: "05", title: "الأدلة", blocks: [{ t: "list", items: s.evidence }] },
      { id: "questions", kicker: "06", title: "أسئلة الفهم", blocks: [{ t: "list", ordered: true, items: s.questions }, { t: "note", text: "هذه القراءة دليل مراجعة مكثّف؛ ارجع إلى نص الكتاب المدرسي عند الاستشهاد الحرفي." }] },
    ],
    quiz: s.quiz,
  };
}

